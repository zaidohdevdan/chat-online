/**
 * Client-side encryption for chat messages.
 *
 * Security model (after Level-1 hardening):
 *
 *  - Each message is encrypted with a fresh AES-256-GCM key (rawMessageKey).
 *  - rawMessageKey is wrapped separately for every recipient using ECDH P-256
 *    ephemeral + HKDF-SHA-256 (the `rk` map).
 *  - The `ck` (conversation key) fallback that derived its key from the public
 *    conversationId has been REMOVED. Without `ck`, the server cannot reconstruct
 *    rawMessageKey even with full DB access.
 *  - If a recipient has no registered public key their entry is absent from `rk`
 *    and they will see "🔒 Mensagem protegida" until they register a key.
 *  - Identity keys are stored in IndexedDB as non-extractable CryptoKey objects
 *    so XSS cannot export the raw private-key bytes.
 *  - encryptMessageBody throws instead of silently falling back to plaintext.
 *
 * Backward compatibility:
 *  - Envelopes generated BEFORE this change may still contain `ck`. decryptMessageBody
 *    still tries `ck` as a last resort so old messages remain readable. New messages
 *    never emit `ck`.
 */

import type { UserSummary } from '../features/auth/types';
import { idbClearAll, idbDelete, idbGet, idbSet } from './idb';

const E2EE_PREFIX = 'e2ee:v1:';

/** localStorage key prefix kept only for one-time migration (read + delete). */
const LEGACY_LS_PREFIX = 'chat_online_e2ee_identity_v1:';

/** IndexedDB key for identity keys. */
const IDB_KEY_PREFIX = 'identity:';

interface StoredIdentityKeys {
  publicKeyJwk: JsonWebKey;
  /** Non-extractable CryptoKey stored natively in IndexedDB. */
  privateKey: CryptoKey;
  publicKeyB64: string;
}

interface E2EEEnvelopeV1 {
  v: 1;
  alg: 'ECDH-P256-HKDF-AES256GCM';
  iv: string;
  salt: string;
  ct: string;
  epk?: JsonWebKey;
  rk?: Record<string, { iv: string; wk: string }>;
  /**
   * Legacy field — present in messages encrypted before the Level-1 hardening.
   * Never generated by new code but still read for backward compatibility.
   */
  ck?: { iv: string; wk: string };
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function bytesToBase64(bytes: Uint8Array): string {
  let binary = '';
  for (let i = 0; i < bytes.byteLength; i++) {
    binary += String.fromCharCode(bytes[i]!);
  }
  return btoa(binary);
}

function base64ToBytes(b64: string): Uint8Array {
  const binary = atob(b64);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    out[i] = binary.charCodeAt(i);
  }
  return out;
}

function hasWebCrypto(): boolean {
  return typeof globalThis.crypto !== 'undefined' && Boolean(globalThis.crypto.subtle);
}

// ---------------------------------------------------------------------------
// IndexedDB key storage (Level-1B)
// ---------------------------------------------------------------------------

/**
 * Migrate a legacy localStorage key pair to IndexedDB (one-time, then deletes LS entry).
 * The private key JWK is re-imported as non-extractable.
 */
async function migrateLegacyKey(userId: string): Promise<StoredIdentityKeys | null> {
  try {
    const raw = localStorage.getItem(`${LEGACY_LS_PREFIX}${userId}`);
    if (!raw) return null;
    const parsed = JSON.parse(raw) as {
      publicKeyJwk: JsonWebKey;
      privateKeyJwk: JsonWebKey;
      publicKeyB64: string;
    };
    if (!parsed.privateKeyJwk || !parsed.publicKeyJwk) return null;

    // Re-import private key as NON-extractable so the bytes can't leave the browser.
    const privateKey = await crypto.subtle.importKey(
      'jwk',
      parsed.privateKeyJwk,
      { name: 'ECDH', namedCurve: 'P-256' },
      false, // non-extractable
      ['deriveBits', 'deriveKey'],
    );

    const record: StoredIdentityKeys = {
      publicKeyJwk: parsed.publicKeyJwk,
      privateKey,
      publicKeyB64: parsed.publicKeyB64,
    };

    await idbSet(`${IDB_KEY_PREFIX}${userId}`, record);
    // Remove from localStorage — private-key bytes must not live there.
    localStorage.removeItem(`${LEGACY_LS_PREFIX}${userId}`);
    return record;
  } catch {
    return null;
  }
}

async function loadIdentityKeys(userId: string): Promise<StoredIdentityKeys | null> {
  if (!userId) return null;
  try {
    const stored = await idbGet<StoredIdentityKeys>(`${IDB_KEY_PREFIX}${userId}`);
    if (stored?.privateKey && stored.publicKeyJwk) return stored;
  } catch {
    // IndexedDB unavailable — fall through to migration attempt
  }

  // One-time migration from localStorage (removes the LS entry on success)
  return migrateLegacyKey(userId);
}

async function generateAndStoreIdentityKeys(userId: string): Promise<StoredIdentityKeys> {
  const keyPair = await crypto.subtle.generateKey(
    { name: 'ECDH', namedCurve: 'P-256' },
    false, // non-extractable: bytes cannot be read from JS
    ['deriveBits', 'deriveKey'],
  );

  const publicKeyJwk = await crypto.subtle.exportKey('jwk', keyPair.publicKey);
  const publicKeyB64 = btoa(JSON.stringify(publicKeyJwk));

  const record: StoredIdentityKeys = {
    publicKeyJwk,
    privateKey: keyPair.privateKey,
    publicKeyB64,
  };

  await idbSet(`${IDB_KEY_PREFIX}${userId}`, record);
  return record;
}

// ---------------------------------------------------------------------------
// Public key management
// ---------------------------------------------------------------------------

export async function ensureUserIdentityPublicKey(userId: string): Promise<string | null> {
  if (!hasWebCrypto() || !userId) return null;
  try {
    const existing = await loadIdentityKeys(userId);
    if (existing) return existing.publicKeyB64;
    const fresh = await generateAndStoreIdentityKeys(userId);
    return fresh.publicKeyB64;
  } catch {
    return null;
  }
}

/** Wipe all identity keys from IndexedDB (call on logout). */
export async function clearIdentityKeys(): Promise<void> {
  try {
    await idbClearAll();
  } catch {
    // Best-effort
  }
}

/** Remove the identity key for a specific user (e.g. after account deletion). */
export async function deleteIdentityKey(userId: string): Promise<void> {
  try {
    await idbDelete(`${IDB_KEY_PREFIX}${userId}`);
  } catch {
    // Best-effort
  }
}

// ---------------------------------------------------------------------------
// ECDH key derivation helpers
// ---------------------------------------------------------------------------

async function deriveECDHWrappingKey(
  privateKey: CryptoKey,
  peerPublicKeyJwk: JsonWebKey,
  salt: Uint8Array,
): Promise<CryptoKey> {
  const peerPub = await crypto.subtle.importKey(
    'jwk',
    peerPublicKeyJwk,
    { name: 'ECDH', namedCurve: 'P-256' },
    false,
    [],
  );
  const sharedBits = await crypto.subtle.deriveBits(
    { name: 'ECDH', public: peerPub },
    privateKey,
    256,
  );
  const hkdfBase = await crypto.subtle.importKey('raw', sharedBits, 'HKDF', false, [
    'deriveKey',
  ]);
  return crypto.subtle.deriveKey(
    {
      name: 'HKDF',
      hash: 'SHA-256',
      salt: salt as unknown as BufferSource,
      info: new TextEncoder().encode('chat-online-x3dh-ecdh-wrap-v1'),
    },
    hkdfBase,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt'],
  );
}

/**
 * Legacy: derive conversation ratchet key from the (public) conversationId.
 * Only used in decryptMessageBody to read old messages that have a `ck` field.
 * Never called during encryption of new messages.
 */
async function deriveConversationRatchetKey(
  conversationId: string,
  salt: Uint8Array,
): Promise<CryptoKey> {
  const enc = new TextEncoder();
  const baseKeyMaterial = await crypto.subtle.importKey(
    'raw',
    enc.encode(`signal-ratchet-root:${conversationId}`),
    'HKDF',
    false,
    ['deriveKey'],
  );
  return crypto.subtle.deriveKey(
    {
      name: 'HKDF',
      hash: 'SHA-256',
      salt: salt as unknown as BufferSource,
      info: enc.encode('chat-online-e2ee-msg-ratchet-v1'),
    },
    baseKeyMaterial,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt'],
  );
}

// ---------------------------------------------------------------------------
// Encrypt / Decrypt
// ---------------------------------------------------------------------------

export function isEncryptedPayload(body: string | null | undefined): boolean {
  return Boolean(body && body.startsWith(E2EE_PREFIX));
}

/**
 * Encrypt plaintext for all recipients that have a registered public key.
 *
 * Level-1A changes:
 *  - `ck` is never generated. The server cannot derive rawMessageKey.
 *  - Throws `EncryptionError` if WebCrypto is unavailable.
 *  - Throws `EncryptionError` if no recipient key was wrapped (rk is empty)
 *    — this prevents silent plaintext fallback.
 */
export class EncryptionError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'EncryptionError';
  }
}

export async function encryptMessageBody(
  plaintext: string,
  // conversationId kept in signature for API compatibility; not used in encryption
  // after Level-1A removed the `ck` field that derived from it.
  _conversationId: string,
  members?: UserSummary[],
): Promise<string> {
  if (!plaintext || isEncryptedPayload(plaintext)) return plaintext;

  if (!hasWebCrypto()) {
    throw new EncryptionError(
      'WebCrypto não disponível neste navegador. Mensagem não enviada.',
    );
  }

  const enc = new TextEncoder();
  const rawMessageKey = crypto.getRandomValues(new Uint8Array(32));
  const msgIv = crypto.getRandomValues(new Uint8Array(12));
  const salt = crypto.getRandomValues(new Uint8Array(16));

  const msgCryptoKey = await crypto.subtle.importKey(
    'raw',
    rawMessageKey,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt'],
  );

  const ctBuffer = await crypto.subtle.encrypt(
    { name: 'AES-GCM', iv: msgIv },
    msgCryptoKey,
    enc.encode(plaintext),
  );

  // Ephemeral ECDH keypair for per-message forward secrecy
  const ephemeralPair = await crypto.subtle.generateKey(
    { name: 'ECDH', namedCurve: 'P-256' },
    true,
    ['deriveBits', 'deriveKey'],
  );
  const epk = await crypto.subtle.exportKey('jwk', ephemeralPair.publicKey);
  const rk: Record<string, { iv: string; wk: string }> = {};

  if (members && members.length > 0) {
    for (const m of members) {
      if (!m.publicKey) continue;
      try {
        const peerJwk = JSON.parse(atob(m.publicKey)) as JsonWebKey;
        const wrapKey = await deriveECDHWrappingKey(ephemeralPair.privateKey, peerJwk, salt);
        const wrapIv = crypto.getRandomValues(new Uint8Array(12));
        const wrapped = await crypto.subtle.encrypt(
          { name: 'AES-GCM', iv: wrapIv },
          wrapKey,
          rawMessageKey,
        );
        rk[m.id] = {
          iv: bytesToBase64(wrapIv),
          wk: bytesToBase64(new Uint8Array(wrapped)),
        };
      } catch {
        // Skip members with invalid or corrupted public key
      }
    }
  }

  // Level-1A: refuse to send if no recipient key was wrapped.
  // This prevents the previous silent plaintext fallback.
  if (Object.keys(rk).length === 0) {
    throw new EncryptionError(
      'Nenhum destinatário possui chave pública registrada. ' +
        'Aguarde o destinatário abrir o app antes de enviar.',
    );
  }

  // No `ck` field — the server cannot derive rawMessageKey.
  const envelope: E2EEEnvelopeV1 = {
    v: 1,
    alg: 'ECDH-P256-HKDF-AES256GCM',
    iv: bytesToBase64(msgIv),
    salt: bytesToBase64(salt),
    ct: bytesToBase64(new Uint8Array(ctBuffer)),
    epk,
    rk,
  };

  return `${E2EE_PREFIX}${btoa(JSON.stringify(envelope))}`;
}

export async function decryptMessageBody(
  payload: string | null | undefined,
  conversationId: string,
  currentUserId?: string,
): Promise<string | null> {
  if (!payload) return null;
  if (!isEncryptedPayload(payload) || !hasWebCrypto()) return payload;

  try {
    const encoded = payload.slice(E2EE_PREFIX.length);
    const env = JSON.parse(atob(encoded)) as E2EEEnvelopeV1;
    const salt = base64ToBytes(env.salt);
    const msgIv = base64ToBytes(env.iv);
    const ctBytes = base64ToBytes(env.ct);

    let rawMessageKey: ArrayBuffer | null = null;

    // 1. Try ECDH P-256 recipient unwrap (rk) — works for messages from new code.
    if (currentUserId && env.epk && env.rk?.[currentUserId]) {
      const keys = await loadIdentityKeys(currentUserId);
      if (keys?.privateKey) {
        try {
          const wrapEntry = env.rk[currentUserId]!;
          const wrapKey = await deriveECDHWrappingKey(keys.privateKey, env.epk, salt);
          rawMessageKey = await crypto.subtle.decrypt(
            { name: 'AES-GCM', iv: base64ToBytes(wrapEntry.iv) as unknown as BufferSource },
            wrapKey,
            base64ToBytes(wrapEntry.wk) as unknown as BufferSource,
          );
        } catch {
          rawMessageKey = null;
        }
      }
    }

    // 2. Legacy fallback: try `ck` for messages encrypted before Level-1A.
    //    New messages never have `ck`; this branch will naturally not trigger for them.
    if (!rawMessageKey && env.ck) {
      try {
        const convKey = await deriveConversationRatchetKey(conversationId, salt);
        rawMessageKey = await crypto.subtle.decrypt(
          { name: 'AES-GCM', iv: base64ToBytes(env.ck.iv) as unknown as BufferSource },
          convKey,
          base64ToBytes(env.ck.wk) as unknown as BufferSource,
        );
      } catch {
        rawMessageKey = null;
      }
    }

    if (!rawMessageKey) {
      return '🔒 Mensagem protegida';
    }

    const msgCryptoKey = await crypto.subtle.importKey(
      'raw',
      rawMessageKey,
      { name: 'AES-GCM', length: 256 },
      false,
      ['decrypt'],
    );
    const plainBuffer = await crypto.subtle.decrypt(
      { name: 'AES-GCM', iv: msgIv as unknown as BufferSource },
      msgCryptoKey,
      ctBytes as unknown as BufferSource,
    );

    return new TextDecoder().decode(plainBuffer);
  } catch {
    return '🔒 Mensagem protegida';
  }
}
